export function localizeShortcut(item: MenuShortcut): MenuShortcut {
  const name = item.title.replace(/^(Quit|Hide|About) (.+)$/, (_, action: string, app: string) => `${({ Quit: "退出", Hide: "隐藏", About: "关于" } as Record<string, string>)[action]} ${app}`);
  return { ...item, title: NATIVE_TITLES[item.id] ?? MENU_LABELS[item.title] ?? name, path: item.path.map((part) => MENU_LABELS[part] ?? part) };
}
